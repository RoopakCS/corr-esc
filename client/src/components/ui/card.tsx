import * as React from "react"
import { cn } from "cn"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { size?: "default" | "sm" }
>(({ className, size = "default", ...props }, ref) => (
  <div
    ref={ref}
    data-slot="card"
    data-size={size}
    className={cn(
      "group/card flex flex-col rounded-xl bg-card text-card-foreground border border-border shadow-xs",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

